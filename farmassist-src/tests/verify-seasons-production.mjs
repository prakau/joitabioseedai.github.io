import { chromium } from "@playwright/test";
import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";

// Opt-in only: one real advisory request uses the existing production quota.
if (process.env.JOITA_LIVE_TESTS !== "1") throw new Error("Set JOITA_LIVE_TESTS=1 to run public provider verification.");
const origin = "https://www.joitabioseedai.com";
const evidence = process.env.JOITA_EVIDENCE_DIR || "test-results/production-seasons";
await mkdir(evidence, { recursive: true });
const browser = await chromium.launch(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE } : {});
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, serviceWorkers: "block", reducedMotion: "reduce" });
  const page = await context.newPage(); page.setDefaultTimeout(65000);
  const errors = [], requests = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("request", request => { if (new URL(request.url()).pathname === "/api/farmassist-chat") requests.push(request.postDataJSON()); });
  const healthResponse = await context.request.get(`${origin}/api/health`);
  const health = await healthResponse.json();
  assert(healthResponse.ok() && health.ok && (health.hasGeminiKey || health.hasOpenRouterKey));
  await page.goto(`${origin}/farmassist/#/crops`);
  await page.getByLabel("Field name", { exact: true }).fill("QA North field");
  await page.getByLabel("Crop name", { exact: true }).fill("Mustard");
  await page.getByLabel("District (optional)").fill("Kurukshetra");
  await page.getByLabel("State (optional)").fill("Haryana");
  await page.getByLabel("Sowing date (optional)").fill("2026-10-15");
  await page.getByLabel("Observed crop stage").selectOption("vegetative");
  await page.getByLabel("Area (optional)").fill("1.5");
  await page.getByLabel("Irrigation method").selectOption("drip");
  await page.getByLabel("Private notes (optional)").fill("QA note excluded from advisory");
  await page.getByRole("button", { name: "Save crop season", exact: true }).click();
  await page.locator(".season-row").waitFor();
  await page.getByRole("button", { name: "Use for new questions", exact: true }).click();
  await page.getByRole("button", { name: "Schedule field check", exact: true }).click();
  await page.getByRole("button", { name: "Schedule field check", exact: true }).click();
  await page.reload();
  const stored = await page.evaluate(() => ({ seasons: JSON.parse(localStorage.getItem("joita-fa-crop-seasons-v1")), plans: JSON.parse(localStorage.getItem("joita-fa-plans-v3")) }));
  assert.equal(stored.seasons.length, 1); assert.equal(stored.plans.length, 1);
  assert.match(stored.plans[0].task, /QA North field/);
  await page.getByRole("button", { name: "हिन्दी", exact: true }).click();
  assert.equal(await page.getByRole("heading", { name: "मेरी फसलें", exact: true }).count(), 1);
  await page.screenshot({ path: `${evidence}/my-crops-hi.png`, fullPage: true });
  await page.getByRole("link", { name: "JOITAFA होम", exact: true }).click();
  assert.match(await page.locator(".active-crop").innerText(), /QA North field/);
  await page.getByLabel("आज आप क्या जानना चाहते हैं?", { exact: true }).fill("Meri sarson ki nichli pattiyan peeli ho rahi hain. Pehle kya jaanch karun?");
  await page.getByRole("button", { name: "JOITAFA से पूछें", exact: true }).click();
  await page.locator(".advisory-result").waitFor();
  const answer = await page.evaluate(() => JSON.parse(localStorage.getItem("joita-fa-questions"))[0]);
  assert.equal(requests.length, 1);
  assert.equal(requests[0].language, "Hindi"); assert.equal(requests[0].crop, "Mustard");
  assert.equal(requests[0].location, "Kurukshetra, Haryana");
  assert.equal(JSON.parse(requests[0].investigation.fieldProfile).area, "1.5 acre");
  assert(!JSON.stringify(requests[0]).includes("QA note excluded"));
  assert(["gemini", "openrouter"].includes(answer.source), `Live reply required, received ${answer.source}`);
  assert.match(answer.answer, /[\u0900-\u097f]/);
  assert.equal(await page.locator(".answer-copy").getAttribute("lang"), "hi-IN");
  assert.match(await page.locator(".header-status").innerText(), /लाइव AI उपलब्ध/);
  await page.screenshot({ path: `${evidence}/live-hindi-advisory.png`, fullPage: true });
  assert.deepEqual(errors, []);
  const result = { origin, timestamp: new Date().toISOString(), health, seasonsPersisted: stored.seasons.length, fieldChecks: stored.plans.length, hindiDashboard: true, chatRequests: requests.length, source: answer.source, answer: answer.answer, privateNotesExcluded: true, browserErrors: errors };
  await writeFile(`${evidence}/result.json`, JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result, null, 2));
  await context.close();
} finally { await browser.close(); }
