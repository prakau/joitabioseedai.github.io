test("damaged records, write failures and stale edits never silently replace a farmer's data", async ({ page }) => {
  await seed(page); await page.goto("./#/crops");
  await page.getByRole("button", { name: "Edit", exact: true }).click();
  await page.evaluate(key => { const rows = JSON.parse(localStorage.getItem(key)!); rows[0].updatedAt = "2026-10-29T11:00:00Z"; localStorage.setItem(key, JSON.stringify(rows)); }, key);
  await page.getByLabel("Field name", { exact: true }).fill("stale edit");
  await page.getByRole("button", { name: "Save crop season", exact: true }).click();
  await expect(page.getByRole("alert")).toContainText("changed in another tab");
  expect(await page.evaluate(key => JSON.parse(localStorage.getItem(key)!)[0].plot, key)).toBe("North field");
  await page.evaluate(key => localStorage.setItem(key, "{broken"), key);
  await page.reload();
  await expect(page.getByRole("alert")).toContainText("need recovery");
  await expect(page.getByRole("button", { name: "Save crop season", exact: true })).toBeDisabled();
  expect(await page.evaluate(key => localStorage.getItem(key), key)).toBe("{broken");
  await page.evaluate(({ key, season }) => { localStorage.setItem(key, JSON.stringify([season])); const original = Storage.prototype.setItem; Storage.prototype.setItem = function(k, v) { if (k === key || k === "joita-fa-plans-v3") throw new DOMException("full", "QuotaExceededError"); return original.call(this, k, v); }; window.dispatchEvent(new CustomEvent("records-changed", { detail: key })); }, { key, season });
  await page.getByRole("button", { name: "Complete season", exact: true }).click();
  await expect(page.getByRole("alert").filter({ hasText: "status could not be saved" })).toBeVisible();
  expect(await page.evaluate(key => JSON.parse(localStorage.getItem(key)!)[0].status, key)).toBe("active");
});
