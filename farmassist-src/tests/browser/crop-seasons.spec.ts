test("one dashboard submit attaches the chosen field, keeps private notes out and isolates other crops", async ({ page }) => {
  const bodies: any[] = [];
  await page.route("**/api/farmassist-chat", route => { bodies.push(route.request().postDataJSON()); return route.fulfill({ json: { ok: true, source: "gemini", language: "Hindi", answer: "पहले पौधों और मिट्टी की नमी जांचें। दवा चुनने से पहले KVK से कारण की पुष्टि करें।" } }); });
  await seed(page);
  await page.getByLabel("What would you like to check today?", { exact: true }).fill("My mustard leaves look yellow. What should I check?");
  await page.getByRole("button", { name: "Ask JOITAFA", exact: true }).click();
  await expect(page.locator(".answer-copy")).toContainText("नमी");
  expect(bodies).toHaveLength(1);
  expect(bodies[0].crop).toBe("Mustard"); expect(bodies[0].location).toBe("Kurukshetra, Haryana"); expect(bodies[0].stage).toBe("vegetative");
  expect(JSON.parse(bodies[0].investigation.fieldProfile).area).toBe("1.5 acre");
  expect(JSON.stringify(bodies[0])).not.toContain(season.notes);
  await page.evaluate(key => { const rows = JSON.parse(localStorage.getItem(key)!); rows[0].area = "9"; localStorage.setItem(key, JSON.stringify(rows)); window.dispatchEvent(new CustomEvent("records-changed", { detail: key })); }, key);
  await page.getByLabel("Your question", { exact: true }).fill("What extra observations should I record?");
  await page.getByRole("button", { name: "Ask JOITAFA", exact: true }).click();
  await expect.poll(() => bodies.length).toBe(2);
  expect(JSON.parse(bodies[1].investigation.fieldProfile).area).toBe("1.5 acre");
  await expect(page.locator(".answer-copy")).toBeVisible();
  await page.getByLabel("Your question", { exact: true }).fill("Tomato leaves are curling. What should I check?");
  await page.getByRole("button", { name: "Ask JOITAFA", exact: true }).click();
  await expect.poll(() => bodies.length).toBe(3);
  expect(bodies[2].crop).toBe("Tomato"); expect(bodies[2].stage).toBe("not sure"); expect(bodies[2].investigation).toBeUndefined();
  expect(bodies[2].history).toHaveLength(0);
  await page.getByRole("button", { name: "New question", exact: true }).click();
  await page.locator(".field-context > summary").click();
  await expect(page.getByLabel("Crop", { exact: true })).toHaveValue("Mustard");
});
