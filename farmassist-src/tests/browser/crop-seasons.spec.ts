async function seed(page: Page) {
  await page.goto("./");
  await page.evaluate(({ key, activeKey, season }) => { localStorage.setItem(key, JSON.stringify([season])); localStorage.setItem(activeKey, JSON.stringify(season.id)); }, { key, activeKey, season });
  await page.reload();
}
